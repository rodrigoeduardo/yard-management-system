/**
 * Pure helpers for driving the local Supabase stack used by
 * `npm run test:integration:setup` (see that script for the CLI entry
 * point). Kept separate so the key-fallback and env-file logic can be unit
 * tested without shelling out to the `supabase` CLI or Docker.
 */

/** Subset of `supabase status -o json` fields this project uses. */
export type LocalSupabaseStatus = {
  API_URL: string;
  DB_URL: string;
  ANON_KEY?: string;
  PUBLISHABLE_KEY?: string;
  SERVICE_ROLE_KEY?: string;
  SECRET_KEY?: string;
};

// Fixed local-only credentials — not secrets, since they only ever exist
// inside the disposable local Supabase stack (never the remote project).
export const LOCAL_TEST_USER_EMAIL = "integration-test@yard.local";
export const LOCAL_TEST_USER_PASSWORD = "integration-test-password";
export const LOCAL_REGISTER_INVITE_CODE = "LOCAL-INTEGRATION-TEST";
export const LOCAL_DEMO_USER_EMAIL = "demo-integration-test@yard.local";
export const LOCAL_DEMO_USER_PASSWORD = "demo-integration-test-password";

/**
 * The Supabase CLI reports the publishable key under different field names
 * depending on the API-key format the local project is using: the newer
 * `PUBLISHABLE_KEY` (`sb_publishable_...`) or the legacy JWT `ANON_KEY`.
 * Prefer the new format; fall back to the legacy one.
 */
export function pickPublishableKey(status: LocalSupabaseStatus): string {
  const key = status.PUBLISHABLE_KEY ?? status.ANON_KEY;
  if (!key) {
    throw new Error(
      "`supabase status` did not report a PUBLISHABLE_KEY or ANON_KEY",
    );
  }
  return key;
}

/** Same fallback as {@link pickPublishableKey}, for the admin/service key. */
export function pickServiceKey(status: LocalSupabaseStatus): string {
  const key = status.SECRET_KEY ?? status.SERVICE_ROLE_KEY;
  if (!key) {
    throw new Error(
      "`supabase status` did not report a SECRET_KEY or SERVICE_ROLE_KEY",
    );
  }
  return key;
}

/**
 * Renders the `.env.test.local` contents consumed by
 * `vitest.setup.integration.ts`. Written to disk (gitignored) so the
 * connection details survive from the setup command into the separate
 * `npm run test:integration` process.
 */
export function buildTestEnvFileContents(status: LocalSupabaseStatus): string {
  return [
    "# Generated by `npm run test:integration:setup` — do not edit by hand.",
    `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${pickPublishableKey(status)}`,
    `SUPABASE_DB_URL=${status.DB_URL}`,
    `TEST_USER_EMAIL=${LOCAL_TEST_USER_EMAIL}`,
    `TEST_USER_PASSWORD=${LOCAL_TEST_USER_PASSWORD}`,
    `REGISTER_INVITE_CODE=${LOCAL_REGISTER_INVITE_CODE}`,
    `DEMO_USER_EMAIL=${LOCAL_DEMO_USER_EMAIL}`,
    `DEMO_USER_PASSWORD=${LOCAL_DEMO_USER_PASSWORD}`,
    "",
  ].join("\n");
}
